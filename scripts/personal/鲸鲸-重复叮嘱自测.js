'use strict';
const assert = require('node:assert');
const { stripRepeatedArrival, stripUnbackedActionClaims, stripUnbackedBrowseClaims, stripUnbackedResearchClaims, stripFalseDocumentClaims, isImmediateDuplicate } = require('../../src/core/phraseRepeat.js');
let p=0,f=0;
function c(n,fn){try{fn();p++;console.log('  ✓ '+n);}catch(e){f++;console.log('  ✗ '+n+' '+e.message);}}
const twice=[{role:'assistant',text:'到家了跟我说一声。'},{role:'assistant',text:'路上小心，到家说一声。'}];
c('连续两次后删除',()=>assert.ok(!stripRepeatedArrival('好，路上小心，到家了跟我说一声。',twice).includes('到家')));
c('保留主内容',()=>assert.ok(stripRepeatedArrival('好，路上小心，到家了跟我说一声。',twice).includes('路上小心')));
c('只出现一次不删',()=>assert.strictEqual(stripRepeatedArrival('到家了跟我说一声。',[twice[0]]),'到家了跟我说一声。'));
c('无叮嘱不改',()=>assert.strictEqual(stripRepeatedArrival('今天有点累。',twice),'今天有点累。'));
c('全删给不催短句',()=>assert.strictEqual(stripRepeatedArrival('到家了跟我说一声。',twice),'好，不催了。'));
c('没动作不声称写好',()=>assert.ok(!stripUnbackedActionClaims('现在写好了也先不给你看').includes('写好了')));
c('没动作不声称写了一张',()=>assert.ok(!stripUnbackedActionClaims('我写了一张，压在盒子最上面').includes('写了一张')));
c('文件没下载不谎称空',()=>assert.ok(stripFalseDocumentClaims('文件本身读不出来，内容空的',{mediaFail:'文件下载失败：本地找不到这个文件'}).includes('没有下载到本地')));
c('无来源查到了被替换',()=>assert.ok(!stripUnbackedResearchClaims('查到了：《流氓叙事》是6人本').includes('查到了')));
c('我写的是不误拦',()=>assert.strictEqual(stripUnbackedActionClaims('我写的是那个老板娘'),'我写的是那个老板娘'));
c('刷回来了无来源替换',()=>assert.ok(!stripUnbackedBrowseClaims('我刷回来了，这轮有几条').includes('刷回来')));
c('这次是真写也拦',()=>assert.ok(!stripUnbackedActionClaims('这次是真写。我写了一张。').includes('真写')));
c('疑问句不误改',()=>assert.strictEqual(stripUnbackedActionClaims('你写好了吗'),'你写好了吗'));
c('保留正常完成',()=>assert.strictEqual(stripUnbackedActionClaims('我想想'),'我想想'));
c('连续 assistant 同句拦截',()=>assert.strictEqual(isImmediateDuplicate('在呢主人，怎么啦',[{role:'assistant',text:'在呢主人，怎么啦'}]),true));
c('有 user 不拦',()=>assert.strictEqual(isImmediateDuplicate('在呢主人，怎么啦',[{role:'assistant',text:'在呢主人，怎么啦'},{role:'user',text:'在吗'}]),false));
c('不同句不拦',()=>assert.strictEqual(isImmediateDuplicate('嗯',[{role:'assistant',text:'在呢主人，怎么啦'}]),false));
console.log('\n通过 '+p+'/'+(p+f));
process.exit(f?1:0);
